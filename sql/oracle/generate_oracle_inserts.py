"""
generate_oracle_inserts.py
--------------------------
Creates the Oracle data-loading scripts from the project's CSV files:

    02_insert_reference_data.sql   <- categories + monthly budgets
    03_insert_transactions.sql     <- all cleaned transactions

Why generate instead of typing by hand?
    1,275 transactions + 288 budget rows is far too many to type, and
    generating from the same CSVs the Python project uses guarantees the
    Oracle data is IDENTICAL to the pandas / SQLite data.

Oracle details handled here:
    * Apostrophes are doubled:  Haldiram's -> 'Haldiram''s'
    * "&" is written as CHR(38): SQL Developer / SQL*Plus would otherwise
      treat "&" as a substitution variable and prompt for a value.
    * Dates use ANSI literals:  DATE '2024-01-05'  (no NLS format issues)
    * Rows are grouped into INSERT ALL statements of 100 rows, so Live SQL
      runs ~20 statements instead of ~1,500 single inserts.

Each generated script ends with verification queries whose EXPECTED
results are written next to them (computed here with pandas).

Run from the project folder:
    python sql/oracle/generate_oracle_inserts.py
"""

from pathlib import Path

import pandas as pd

ORACLE_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = ORACLE_DIR.parent.parent
CLEAN_FILE = PROJECT_ROOT / "data" / "processed" / "transactions_clean.csv"
BUDGET_FILE = PROJECT_ROOT / "data" / "raw" / "monthly_budget.csv"

ROWS_PER_STATEMENT = 100


def sql_text(value):
    """Turn a Python string into a safe Oracle string literal."""
    if pd.isna(value):
        return "NULL"
    text = str(value).replace("'", "''")             # escape apostrophes
    literal = "'" + text + "'"
    return literal.replace("&", "' || CHR(38) || '")  # avoid substitution prompts


def sql_money(value):
    return f"{float(value):.2f}"


def insert_all(table, columns, rows):
    """Build INSERT ALL statements, ROWS_PER_STATEMENT rows each."""
    statements = []
    # Oracle rule: one INSERT ALL may target at most 999 columns in total
    assert ROWS_PER_STATEMENT * len(columns) <= 999, "INSERT ALL would exceed 999 columns"
    col_list = ", ".join(columns)
    for start in range(0, len(rows), ROWS_PER_STATEMENT):
        chunk = rows[start:start + ROWS_PER_STATEMENT]
        lines = [f"    INTO {table} ({col_list}) VALUES ({', '.join(r)})" for r in chunk]
        statements.append("INSERT ALL\n" + "\n".join(lines) + "\nSELECT 1 FROM dual;\n")
    return statements


def header(title, purpose):
    return f"""-- =====================================================================
-- {title}
-- {purpose}
-- GENERATED by sql/oracle/generate_oracle_inserts.py from the project CSVs.
-- Do not edit by hand - re-run the generator instead.
-- Requires: 01_create_schema.sql has been run.
-- =====================================================================

"""


def build_reference_script(txns, budget):
    # One row per category, taken from the cleaned data (same as src/sql_analysis.py)
    cats = (txns[["category", "expense_type", "cost_nature"]]
            .drop_duplicates("category").sort_values("category"))
    cat_rows = [[sql_text(r.category), sql_text(r.expense_type), sql_text(r.cost_nature)]
                for r in cats.itertuples()]

    # '2024-01' in the CSV becomes DATE '2024-01-01' (first day of month)
    bud_rows = [[f"DATE '{r.month}-01'", sql_text(r.category), sql_money(r.budget_amount)]
                for r in budget.itertuples()]

    parts = [header("02_insert_reference_data.sql",
                    f"Loads {len(cats)} categories and {len(budget)} monthly budget rows.")]
    parts.append("-- Clear old data (children first because of foreign keys)\n"
                 "DELETE FROM budget_alerts;\nDELETE FROM transactions;\n"
                 "DELETE FROM budgets;\nDELETE FROM categories;\n\n")
    parts.append(f"-- ---------- categories ({len(cats)} rows) ----------\n")
    parts += insert_all("categories", ["category_name", "category_group", "cost_nature"], cat_rows)
    parts.append(f"\n-- ---------- budgets ({len(budget)} rows) ----------\n")
    parts += insert_all("budgets", ["budget_month", "category", "budget_amount"], bud_rows)
    parts.append("\nCOMMIT;\n\n")

    parts.append(f"""-- ---------- Verification ----------
-- EXPECTED: categories = {len(cats)}, budget_rows = {len(budget)},
--           total_budget = {budget['budget_amount'].sum():,.2f},
--           first_month = 01-JAN-{budget['month'].min()[:4]}, last_month = 01-DEC-{budget['month'].max()[:4]}
SELECT (SELECT COUNT(*) FROM categories)          AS categories,
       (SELECT COUNT(*) FROM budgets)             AS budget_rows,
       (SELECT SUM(budget_amount) FROM budgets)   AS total_budget,
       (SELECT MIN(budget_month) FROM budgets)    AS first_month,
       (SELECT MAX(budget_month) FROM budgets)    AS last_month
FROM dual;
""")
    return "".join(parts)


def build_transactions_script(txns):
    # Only the 8 source columns are inserted; trg_transactions_derive fills
    # year_month, day_of_week and is_weekend from txn_date automatically.
    columns = ["transaction_id", "txn_date", "description", "category",
               "amount", "txn_type", "payment_mode", "merchant"]
    rows = [[sql_text(r.transaction_id), f"DATE '{r.date}'", sql_text(r.description),
             sql_text(r.category), sql_money(r.amount), sql_text(r.txn_type),
             sql_text(r.payment_mode), sql_text(r.merchant)]
            for r in txns.itertuples()]

    debit = txns[txns["txn_type"] == "Debit"]
    credit = txns[txns["txn_type"] == "Credit"]
    weekend = txns["is_weekend"].astype(str).str.lower().eq("true").sum()

    parts = [header("03_insert_transactions.sql",
                    f"Loads {len(txns):,} cleaned transactions "
                    f"({txns['date'].min()} to {txns['date'].max()}).")]
    parts.append("DELETE FROM budget_alerts;\nDELETE FROM transactions;\n\n")
    parts += insert_all("transactions", columns, rows)
    parts.append("\nCOMMIT;\n\n")
    parts.append(f"""-- ---------- Verification ----------
-- EXPECTED (same numbers as the Python analysis):
--   Credit : {len(credit):>5} rows, total {credit['amount'].sum():>14,.2f}
--   Debit  : {len(debit):>5} rows, total {debit['amount'].sum():>14,.2f}
SELECT txn_type, COUNT(*) AS num_rows, SUM(amount) AS total_amount
FROM   transactions
GROUP  BY txn_type
ORDER  BY txn_type;

-- EXPECTED: weekend_rows = {weekend}, missing_derived = 0
-- (checks that the trigger filled the derived columns)
SELECT SUM(is_weekend) AS weekend_rows,
       SUM(CASE WHEN year_month IS NULL OR day_of_week IS NULL THEN 1 ELSE 0 END) AS missing_derived
FROM   transactions;
""")
    return "".join(parts)


def main():
    txns = pd.read_csv(CLEAN_FILE)
    budget = pd.read_csv(BUDGET_FILE)

    # Safety checks so the generated SQL always fits the Oracle columns
    assert txns["description"].str.len().max() <= 100, "description longer than VARCHAR2(100)"
    assert txns["merchant"].str.len().max() <= 60, "merchant longer than VARCHAR2(60)"
    assert txns["transaction_id"].is_unique, "duplicate transaction IDs"

    (ORACLE_DIR / "02_insert_reference_data.sql").write_text(build_reference_script(txns, budget), encoding="utf-8")
    (ORACLE_DIR / "03_insert_transactions.sql").write_text(build_transactions_script(txns), encoding="utf-8")
    print(f"Wrote 02_insert_reference_data.sql and 03_insert_transactions.sql "
          f"({len(txns):,} transactions, {len(budget)} budget rows)")


if __name__ == "__main__":
    main()
